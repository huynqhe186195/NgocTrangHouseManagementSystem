using System;
using System.Linq;
using System.Threading.Tasks;
using BuildingManagement.Buildings;
using BuildingManagement.EntityFrameworkCore;
using BuildingManagement.EntityFrameworkCore.Security;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using Xunit;

namespace BuildingManagement.PostgreSqlTests;

/// <summary>
/// Rehearses CURRENT, UNMODIFIED runtime migration chain followed by the
/// unregistered Slice A migration, on a freshly generated disposable
/// PostgreSQL DATABASE. Opt-in is required even on localhost. Never touches
/// ngoctrang_integration_test's public tables or a production connection.
/// </summary>
public sealed class SliceAFullChainUpgradePostgreSql_Tests
{
    private const string OptIn = "BM_PG_SLICE_A_FULL_CHAIN_OPT_IN";
    private const string Accepted = "CREATE_AND_DROP_RANDOM_LOCAL_SLICE_A_DATABASE";
    private const string ScratchMigration = "202610280001_SliceAGrantScratch";

    [Fact]
    public async Task PGCHAIN01_Existing_Buildings_Survive_Full_Chain_Grant_Upgrade_And_History_Guard()
    {
        if (Environment.GetEnvironmentVariable(OptIn) != Accepted)
            throw new InvalidOperationException(
                "Explicit isolated full-chain PostgreSQL opt-in required.");

        var allowed = BuildingManagementPostgreSqlTestModule
            .RequireSafeConnectionString();
        var adminOptions = new NpgsqlConnectionStringBuilder(allowed)
        {
            Pooling = false, CommandTimeout = 90
        };
        var randomDb = "bm_slicea_rehearsal_" + Guid.NewGuid().ToString("N");

        // All identifiers were generated by this method. NEVER use client
        // input, app connection names or an existing database for DROP.
        Assert.Matches(@"^bm_slicea_rehearsal_[0-9a-f]{32}$", randomDb);
        await using var admin = new NpgsqlConnection(adminOptions.ConnectionString);
        await admin.OpenAsync();
        Assert.Equal(BuildingManagementPostgreSqlTestModule.DatabaseName,
            admin.Database);

        // Refuse CREATE if this is not a dedicated capable local test role.
        await using (var privilege = new NpgsqlCommand(
            "SELECT rolcreatedb OR rolsuper FROM pg_roles WHERE rolname = current_user",
            admin))
            Assert.True((bool)(await privilege.ExecuteScalarAsync() ?? false),
                "Dedicated local test role must explicitly allow scratch DB creation.");

        var created = false;
        try
        {
            await ExecAsync(admin,
                $"CREATE DATABASE \"{randomDb}\" TEMPLATE template0");
            created = true;
            var scoped = new NpgsqlConnectionStringBuilder(adminOptions.ConnectionString)
            {
                Database = randomDb,
                Pooling = false,
                CommandTimeout = 120
            }.ConnectionString;
            Guid existingA = Guid.NewGuid(), existingB = Guid.NewGuid();
            var owner = Guid.NewGuid();

            var runtimeOptions = new DbContextOptionsBuilder<BuildingManagementDbContext>()
                .UseNpgsql(scoped).Options;
            string[] baselineMigrations;
            await using (var existing = new BuildingManagementDbContext(runtimeOptions))
            {
                baselineMigrations = existing.Database.GetMigrations().ToArray();
                Assert.NotEmpty(baselineMigrations);
                Assert.Empty(await existing.Database.GetAppliedMigrationsAsync());
                await existing.Database.MigrateAsync();
                Assert.Equal(baselineMigrations,
                    (await existing.Database.GetAppliedMigrationsAsync()).ToArray());
                // Direct SQL seeds EXISTING rows. This manually created
                // AbpDbContext has no ABP lazy services for SaveChanges
                // audit interception; MigrateAsync itself is still REAL.
                await existing.Database.ExecuteSqlInterpolatedAsync($"""
                    INSERT INTO "Buildings"
                    ("Id","Name","Address","ExtraProperties","ConcurrencyStamp",
                     "CreationTime","IsDeleted")
                    VALUES ({existingA}, {"Existing Building A"}, {"Old address A"},
                            '{{}}', {Guid.NewGuid().ToString("N")}, CURRENT_TIMESTAMP, FALSE)
                    """);
                await existing.Database.ExecuteSqlInterpolatedAsync($"""
                    INSERT INTO "Buildings"
                    ("Id","Name","Address","ExtraProperties","ConcurrencyStamp",
                     "CreationTime","IsDeleted")
                    VALUES ({existingB}, {"Existing Building B"}, {"Old address B"},
                            '{{}}', {Guid.NewGuid().ToString("N")}, CURRENT_TIMESTAMP, FALSE)
                    """);
            }

            // The reviewed Slice A EF migration is in the TEST assembly,
            // not in the production DbMigrator's assembly/model snapshot.
            await using (var grants = OpenGrantDb(scoped))
            {
                await grants.Database.MigrateAsync();
                Assert.Contains(ScratchMigration,
                    await grants.Database.GetAppliedMigrationsAsync());

                // Seed a historical owner grant on one PRE-EXISTING
                // building. No new building or owner account is inferred.
                grants.Grants.Add(BuildingOperatorAccessGrant.Issue(
                    Guid.NewGuid(), owner, existingA, owner,
                    DateTime.UtcNow.AddMinutes(-1), null));
                await grants.SaveChangesAsync();

                Assert.Equal(2, await grants.Buildings.CountAsync());
                Assert.Equal(1, await grants.Grants.CountAsync());
                await Assert.ThrowsAsync<PostgresException>(() =>
                    grants.Database.MigrateAsync("0"));
                Assert.Contains(ScratchMigration,
                    await grants.Database.GetAppliedMigrationsAsync());
            }

            await using (var intact = new BuildingManagementDbContext(runtimeOptions))
            {
                Assert.Equal(baselineMigrations,
                    (await intact.Database.GetAppliedMigrationsAsync())
                        .Where(m => m != ScratchMigration).ToArray());
                Assert.Equal("Existing Building A",
                    (await intact.Buildings.SingleAsync(x => x.Id == existingA)).Name);
                Assert.Equal("Existing Building B",
                    (await intact.Buildings.SingleAsync(x => x.Id == existingB)).Name);
            }

            await using var verify = OpenGrantDb(scoped);
            var actor = new EfBuildingOperatorGrantCandidateReader(
                verify, TimeProvider.System);
            Assert.Equal(new[] { existingA },
                await actor.GetActiveBuildingIdsAsync(owner));
            Assert.Empty(await actor.GetActiveBuildingIdsAsync(Guid.NewGuid()));
        }
        finally
        {
            if (created)
            {
                // Pooling disabled; all DbContexts and connections disposed.
                // Never drop an existing or user-selected database.
                await ExecAsync(admin, $"DROP DATABASE \"{randomDb}\"");
            }
        }
        await using var noLeftovers = new NpgsqlCommand(
            "SELECT count(*) FROM pg_database WHERE datname = @db", admin);
        noLeftovers.Parameters.AddWithValue("db", randomDb);
        Assert.Equal(0L, Convert.ToInt64(await noLeftovers.ExecuteScalarAsync()));
    }

    private static SliceAGrantScratchDb OpenGrantDb(string cs)
        => new(new DbContextOptionsBuilder<SliceAGrantScratchDb>()
            .UseNpgsql(cs, options => options.MigrationsAssembly(
                typeof(SliceAGrantScratchMigration).Assembly.FullName))
            .Options);

    private static async Task ExecAsync(NpgsqlConnection db, string sql)
    {
        await using var command = new NpgsqlCommand(sql, db);
        await command.ExecuteNonQueryAsync();
    }
}
